import { z } from "zod";
import { marketRowSchema } from "@/cala/domain/analytics/market";
import { isDate } from "@/cala/domain/shared/dates";
import { AMENITY_KEYS } from "@/cala/domain/properties/options";
import { workspacePreferencesSchema } from "@/cala/domain/workspace/preferences";
const id = z.string().min(1).max(100),
  name = z.string().trim().min(1).max(160),
  text = z.string().trim().max(2000),
  date = z.string().refine(isDate, "Fecha inválida"),
  money = z.number().int().min(0).max(100000000000),
  version = z.number().int().positive();
const paymentFields = {
  concept: z.enum([
    "prepayment",
    "payment",
    "refund",
    "deposit",
    "deposit_return",
  ]),
  method: z.enum(["cash", "transfer", "card", "stripe", "paypal", "ota", "other"]),
  amountMinor: money.positive(),
  status: z.enum(["succeeded", "pending"]),
  paidOn: date,
  note: z.string().trim().max(500),
};
/** OTAs the connection assistant can register (see domain/messaging/ota.ts). */
export const otaProviders = [
  "airbnb",
  "booking",
  "expedia",
  "vrbo",
  "google",
  "tripadvisor",
] as const;
export const concepts = [
  "entire_home",
  "hotel",
  "boutique_hotel",
  "villas",
  "apartments",
  "aparthotel",
  "hostel",
  "bed_and_breakfast",
  "inn",
  "cabins",
  "glamping",
  "resort",
  "camping",
  "multi_unit_complex",
  "other",
] as const;
export const roles = [
  "owner",
  "admin",
  "manager",
  "front_desk",
  "housekeeping",
  "finance",
  "viewer",
] as const;
const base = { organizationId: id, propertyId: id };
export const commandSchema = z.discriminatedUnion("type", [
  z.object({
    type: z.literal("workspace.preferences.save"),
    organizationId: id,
    version: z.number().int().min(0),
    preferences: workspacePreferencesSchema,
  }),
  z.object({
    type: z.literal("market.import"),
    ...base,
    rows: z.array(marketRowSchema).min(1).max(366),
  }),
  z.object({
    type: z.literal("conversation.update"),
    ...base,
    reservationId: id,
    version: version.optional(),
    status: z.enum(["open", "archived"]),
    assigneeId: id.nullable(),
  }),
  z.object({
    type: z.literal("message.save"),
    ...base,
    reservationId: id,
    id: id.optional(),
    version: version.optional(),
    mode: z.enum(["draft", "note", "prepare"]),
    subject: z.string().trim().max(200),
    body: z.string().trim().min(1).max(10000),
    scheduledAt: z.iso.datetime({ offset: true }).nullable(),
  }),
  z.object({ type: z.literal("message.cancel"), ...base, id, version }),
  z.object({
    type: z.literal("template.save"),
    ...base,
    id: id.optional(),
    version: version.optional(),
    name,
    locale: z.enum([
      "es",
      "en",
      "de",
      "fr",
      "it",
      "pt",
      "nl",
      "pl",
      "el",
      "hu",
    ]),
    subject: z.string().trim().max(200),
    body: z.string().trim().min(1).max(10000),
    trigger: z.enum(["manual", "booking", "arrival", "departure"]),
    offsetDays: z.number().int().min(-30).max(30),
  }),
  z.object({ type: z.literal("template.delete"), ...base, id, version }),
  z.object({ type: z.literal("ical.rotate"), ...base, unitId: id }),
  z.object({ type: z.literal("ical.revoke"), ...base, unitId: id }),
  z.object({
    type: z.literal("ical.import"),
    ...base,
    unitId: id,
    calendar: name,
    content: z.string().max(100000),
  }),
  z.object({ type: z.literal("organization.create"), name }),
  z.object({
    type: z.literal("onboarding.save"),
    organizationId: id,
    step: z.number().int().min(0).max(8),
    data: z.record(z.string().max(80), z.string().max(2000)),
  }),
  z.object({
    type: z.literal("property.create"),
    organizationId: id,
    name,
    concept: z.enum(concepts),
    city: name,
    address: text,
    currency: z.enum(["MXN", "USD", "EUR"]),
    timezone: z.string().refine((v) => {
      try {
        new Intl.DateTimeFormat("es", { timeZone: v });
        return true;
      } catch {
        return false;
      }
    }),
    unitCount: z.number().int().min(1).max(100),
    maxOccupancy: z.number().int().min(1).max(100),
    baseRateMinor: money,
    sellMode: z.enum(["unit", "bed", "both"]),
    bedrooms: z.number().int().min(0).max(100).default(1),
    beds: z.number().int().min(1).max(100).default(1),
    bathrooms: z.number().int().min(0).max(100).default(1),
    amenities: z.array(z.enum(AMENITY_KEYS)).max(30).default([]),
    checkIn: z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/),
    checkOut: z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/),
    policy: text,
    taxBps: z.number().int().min(0).max(10000),
  }),
  z.object({
    type: z.literal("property.update"),
    ...base,
    name,
    city: name,
    policy: text,
    allowedOverbooking: z.number().int().min(0).max(10),
    address: text.optional(),
    concept: z.enum(concepts).optional(),
    checkIn: z
      .string()
      .regex(/^\d{2}:\d{2}$/)
      .optional(),
    checkOut: z
      .string()
      .regex(/^\d{2}:\d{2}$/)
      .optional(),
    taxBps: z.number().int().min(0).max(10000).optional(),
    version,
  }),
  z.object({
    type: z.literal("guest.save"),
    ...base,
    id: id.optional(),
    firstName: name,
    lastName: name,
    email: z.union([z.email(), z.literal("")]),
    phone: z.union([z.string().regex(/^\+[1-9]\d{6,14}$/), z.literal("")]),
    country: z.string().regex(/^[A-Z]{2}$/),
    notes: text,
    company: z.string().trim().max(160).optional(),
    address: z.string().trim().max(400).optional(),
    city: z.string().trim().max(160).optional(),
    region: z.string().trim().max(160).optional(),
    postalCode: z.string().trim().max(32).optional(),
    language: z
      .string()
      .trim()
      .max(35)
      .regex(/^$|^[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/)
      .optional(),
    version: version.optional(),
  }),
  z.object({
    type: z.literal("inventory.create"),
    ...base,
    name,
    sellMode: z.enum(["unit", "bed"]),
    maxOccupancy: z.number().int().min(1).max(100),
    baseRateMinor: money,
    unitCount: z.number().int().min(1).max(100),
    parentUnitId: id.nullable(),
    amenities: z.array(name).max(30),
  }),
  z.object({
    type: z.literal("inventory.update"),
    ...base,
    id,
    name,
    maxOccupancy: z.number().int().min(1).max(100),
    baseRateMinor: money,
    active: z.boolean(),
  }),
  z.object({
    type: z.literal("unit.update"),
    ...base,
    id,
    name,
    inventoryTypeId: id,
    active: z.boolean(),
    attributes: z
      .object({
        bedrooms: z.number().int().min(0).max(50),
        beds: z.number().int().min(0).max(100),
        bathrooms: z.number().int().min(0).max(50),
      })
      .optional(),
    version,
  }),
  z.object({
    type: z.literal("unit.create"),
    ...base,
    inventoryTypeId: id,
    name,
    parentUnitId: id.nullable(),
  }),
  z.object({
    type: z.literal("block.create"),
    ...base,
    unitId: id,
    arrival: date,
    departure: date,
    reason: name,
  }),
  z.object({ type: z.literal("block.release"), ...base, id }),
  z.object({
    type: z.literal("reservation.save"),
    ...base,
    id: id.optional(),
    guestId: id,
    inventoryTypeId: id,
    unitId: id.nullable(),
    ratePlanId: id,
    arrival: date,
    departure: date,
    adults: z.number().int().min(1).max(100),
    children: z.number().int().min(0).max(100),
    notes: text,
    status: z.enum(["draft", "pending", "confirmed"]),
    version: version.optional(),
  }),
  z.object({
    type: z.literal("reservation.move"),
    ...base,
    id,
    version,
    unitId: id,
    arrival: date,
    departure: date,
    pricing: z.enum(["preserve", "recalculate"]),
  }),
  z.object({
    type: z.literal("reservation.transition"),
    ...base,
    id,
    status: z.enum([
      "confirmed",
      "checked_in",
      "checked_out",
      "cancelled",
      "no_show",
    ]),
    version,
  }),
  z.object({
    type: z.literal("rates.bulk"),
    ...base,
    ratePlanId: id,
    inventoryTypeId: id,
    arrival: date,
    departure: date,
    amountMinor: money,
    minStay: z.number().int().min(1).max(730),
    maxStay: z.number().int().min(1).max(730),
    closed: z.boolean(),
    cta: z.boolean(),
    ctd: z.boolean(),
    expectedVersions: z.record(z.string(), z.number().int().min(0)),
  }),
  z.object({ type: z.literal("ratePlan.create"), ...base, name }),
  z.object({
    type: z.literal("task.save"),
    ...base,
    id: id.optional(),
    unitId: id.nullable(),
    kind: z.enum(["housekeeping", "maintenance"]),
    title: name,
    status: z.enum(["pending", "in_progress", "completed"]),
    priority: z.enum(["normal", "high"]),
    assigneeId: id.nullable(),
    version: version.optional(),
  }),
  z.object({
    type: z.literal("room.create"),
    ...base,
    name,
    parentUnitId: id.nullable(),
    maxOccupancy: z.number().int().min(1).max(100),
    baseRateMinor: money,
  }),
  z.object({
    type: z.literal("room.update"),
    ...base,
    id,
    name,
    maxOccupancy: z.number().int().min(1).max(100),
    baseRateMinor: money,
    active: z.boolean(),
    attributes: z
      .object({
        bedrooms: z.number().int().min(0).max(50),
        beds: z.number().int().min(0).max(100),
        bathrooms: z.number().int().min(0).max(50),
      })
      .optional(),
    version,
  }),
  z.object({
    type: z.literal("room.delete"),
    ...base,
    id,
    version,
  }),
  z.object({
    type: z.literal("property.rentalMode"),
    ...base,
    mode: z.enum(["whole", "rooms", "both"]),
  }),
  z.object({
    type: z.literal("unit.clean"),
    ...base,
    id,
    status: z.enum(["clean", "dirty", "inspected"]),
    version,
  }),
  z.object({
    type: z.literal("folio.charge"),
    ...base,
    reservationId: id,
    description: name,
    amountMinor: money,
  }),
  z.object({
    type: z.literal("payment.create"),
    ...base,
    reservationId: id,
    amountMinor: money.positive(),
    simulateFailure: z.boolean(),
  }),
  z.object({
    type: z.literal("payment.record"),
    ...base,
    reservationId: id,
    ...paymentFields,
  }),
  z.object({
    type: z.literal("payment.update"),
    ...base,
    id,
    ...paymentFields,
  }),
  z.object({ type: z.literal("payment.delete"), ...base, id }),
  z.object({ type: z.literal("channel.create"), ...base, name }),
  z.object({
    type: z.literal("channel.update"),
    ...base,
    id,
    ownership: z.enum(["pms", "channel"]),
    syncMode: z.enum(["ari", "all"]),
    simulateFailure: z.boolean(),
    status: z.enum(["connected", "disconnected", "error"]),
    mappings: z
      .array(z.object({ inventoryTypeId: id, ratePlanId: id, externalId: id }))
      .max(200),
    version,
  }),
  z.object({ type: z.literal("channel.sync"), ...base, id }),
  z.object({
    type: z.literal("channel.connect"),
    ...base,
    provider: z.enum(otaProviders),
    name,
    ownership: z.enum(["pms", "channel"]),
    syncMode: z.enum(["ari", "all"]),
    mappings: z
      .array(
        z.object({
          inventoryTypeId: id,
          ratePlanId: id,
          externalId: z.string().trim().min(1).max(120),
        }),
      )
      .max(200),
  }),
  z.object({ type: z.literal("channel.disconnect"), ...base, id, version }),
  z.object({
    type: z.literal("migration.start"),
    ...base,
    includeConflicts: z.boolean(),
  }),
  z.object({
    type: z.literal("migration.review"),
    ...base,
    id,
    excludeIds: z.array(id).max(1000),
  }),
  z.object({ type: z.literal("job.retry"), ...base, id }),
  z.object({
    type: z.literal("automation.save"),
    ...base,
    id: id.optional(),
    name,
    trigger: z.enum([
      "reservation.created",
      "reservation.cancelled",
      "checkout.completed",
    ]),
    action: z.enum(["create_task", "notify_team"]),
    enabled: z.boolean(),
  }),
  z.object({
    type: z.literal("team.update"),
    organizationId: id,
    id,
    role: z.enum(roles),
    status: z.enum(["active", "suspended"]),
    propertyIds: z.array(id),
  }),
  z.object({
    type: z.literal("team.remove"),
    organizationId: id,
    id,
  }),
  z.object({
    type: z.literal("team.invite"),
    organizationId: id,
    name,
    email: z.email(),
    role: z.enum(roles),
    propertyIds: z.array(id),
  }),
  z.object({
    type: z.literal("report.generate"),
    ...base,
    arrival: date,
    departure: date,
  }),
]);
export type Command = z.infer<typeof commandSchema>;
